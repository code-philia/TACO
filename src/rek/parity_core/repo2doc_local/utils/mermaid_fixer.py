"""
Mermaid syntax fixer.

Automatically repair common Mermaid syntax errors generated by LLMs.
"""

import re

def fix_mermaid_syntax(markdown_content: str) -> str:
    """
    Fix Mermaid syntax errors inside Markdown content.
    
    Args:
        markdown_content: Original Markdown content
        
    Returns:
        Fixed content
    """
    # Match Mermaid code fences.
    pattern = r"```mermaid\n(.*?)```"
    
    def replace_block(match):
        content = match.group(1)
        fixed_content = _fix_mermaid_block(content)
        return f"```mermaid\n{fixed_content}```"
    
    return re.sub(pattern, replace_block, markdown_content, flags=re.DOTALL)


def _fix_mermaid_block(content: str) -> str:
    """Fix a single Mermaid code block."""
    lines = content.split('\n')
    fixed_lines = []
    
    # Node definition regex: ID[Text], ID(Text), and related forms.
    # Capture groups:
    # 1: ID
    # 2: opening delimiter
    # 3: text
    # 4: closing delimiter
    node_pattern = re.compile(r'([A-Za-z0-9_]+)\s*(\[|\(|\{\{|\(\[|\[\()(.+?)(\]|\)|\}\}|\)\]|\)\])')
    
    for line in lines:
        line = line.rstrip()
        if not line:
            fixed_lines.append(line)
            continue
            
        # Try to repair node definitions.
        # Search all node definitions in the line.
        def fix_node(match):
            node_id = match.group(1)
            open_sym = match.group(2)
            text = match.group(3)
            close_sym = match.group(4)
            
            # If already quoted, keep the original text.
            if text.startswith('"') and text.endswith('"'):
                return match.group(0)
            
            # Replace internal double quotes.
            text = text.replace('"', "'")
            
            # Force double quotes around node text.
            # Different shapes have different syntax, but quoted text works for all.
            # Example: A[Text] -> A["Text"]
            # A(Text) -> A("Text")
            return f'{node_id}{open_sym}"{text}"{close_sym}'
            
        # Replace node definitions.
        # This simple regex does not handle every nested case, but covers common errors.
        try:
            # Skip lines that already contain quoted node text.
            if '["' not in line and '("' not in line:
                line = node_pattern.sub(fix_node, line)
        except Exception:
            pass  # Keep the original line if repair fails.
            
        # Repair edge labels with special characters.
        # A -->|Text| B  =>  A -->|"Text"| B
        arrow_pattern = re.compile(r'(\|)([^"]+?)(\|)')
        def fix_arrow(match):
            return f'|"{match.group(2)}"|'
            
        if '-->|' in line or '-.->|' in line:
            try:
                line = arrow_pattern.sub(fix_arrow, line)
            except Exception:
                pass
                
        fixed_lines.append(line)
        
    return '\n'.join(fixed_lines)
